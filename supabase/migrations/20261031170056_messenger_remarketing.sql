create index messenger_remarketing_product_idx
  on public.messenger_remarketing_cycles(product_id);

create table public.messenger_remarketing_attempts (
  id uuid primary key default gen_random_uuid(),
  cycle_id uuid not null references public.messenger_remarketing_cycles(id) on delete cascade,
  step smallint not null check (step between 1 and 2),
  idempotency_key uuid not null default gen_random_uuid() unique,
  status text not null default 'sending' check (status in (
    'sending', 'sent', 'retryable', 'failed', 'uncertain'
