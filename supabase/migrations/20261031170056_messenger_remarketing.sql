create or replace function public.remarketing_effective_due(
  p_due timestamptz,
  p_expires timestamptz,
  p_quiet_start time,
  p_quiet_end time
) returns timestamptz
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_local timestamp;
  v_adjusted timestamptz;
begin
  v_local := p_due at time zone 'Asia/Ho_Chi_Minh';
  if v_local::time >= p_quiet_start then
    v_local := (v_local::date + 1) + p_quiet_end;
  elsif v_local::time < p_quiet_end then
    v_local := v_local::date + p_quiet_end;
  end if;
  v_adjusted := v_local at time zone 'Asia/Ho_Chi_Minh';
  if v_adjusted >= p_expires then return null; end if;
  return v_adjusted;
end;
$$;

create or replace function public.remarketing_start_cycle(
  p_page_id text,
  p_conversation_id uuid,
  p_customer_psid text,
  p_product_id bigint,
  p_intro_version text,
  p_last_customer_interaction_at timestamptz,
  p_intro_completed_at timestamptz,
  p_has_measurements boolean default false,
  p_source_ad_id text default null
) returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_config public.messenger_remarketing_config;
  v_existing public.messenger_remarketing_cycles;
  v_due timestamptz;
  v_expires timestamptz;
  v_cycle public.messenger_remarketing_cycles;
begin
  select * into v_config from public.messenger_remarketing_config where singleton = true for share;
  if not v_config.enabled or v_config.rollout_at is null then
    return jsonb_build_object('started', false, 'reason', 'disabled');
  end if;
  if p_intro_completed_at < v_config.rollout_at then
    return jsonb_build_object('started', false, 'reason', 'before_rollout');
  end if;
  if not (p_product_id = any(v_config.target_product_ids)) then
    return jsonb_build_object('started', false, 'reason', 'product_not_targeted');
  end if;
  if p_has_measurements then
    return jsonb_build_object('started', false, 'reason', 'measurements_known');
  end if;
  if not exists (
    select 1 from public.conversations c join public.products p on p.id = p_product_id
    where c.id = p_conversation_id and c.external_user_id = p_customer_psid
      and c.current_product_id = p_product_id and p.status = 'active'
  ) then
    return jsonb_build_object('started', false, 'reason', 'context_changed');
  end if;
  select * into v_existing from public.messenger_remarketing_cycles
    where page_id = p_page_id and customer_psid = p_customer_psid
      and product_id = p_product_id and intro_version = p_intro_version;
  if found then
    return jsonb_build_object('started', false, 'reason', 'already_exists', 'cycle_id', v_existing.id);
  end if;
  update public.messenger_remarketing_cycles
    set status = 'cancelled', cancel_reason = 'new_cycle', completed_at = now(),
        claim_token = null, lease_until = null, updated_at = now()
    where page_id = p_page_id and customer_psid = p_customer_psid
      and status in ('scheduled', 'claimed');
  v_expires := p_last_customer_interaction_at
    + interval '24 hours' - make_interval(mins => v_config.window_safety_minutes);
  v_due := public.remarketing_effective_due(
    p_intro_completed_at + make_interval(mins => v_config.first_delay_minutes),
    v_expires, v_config.quiet_start, v_config.quiet_end
  );
  if v_due is null or v_due <= p_intro_completed_at or v_due >= v_expires then
    return jsonb_build_object('started', false, 'reason', 'outside_window');
  end if;
  insert into public.messenger_remarketing_cycles(
    page_id, conversation_id, customer_psid, product_id, intro_version,
    source_ad_id, last_customer_interaction_at, intro_completed_at,
    due_at, window_expires_at, has_measurements
  ) values (
    p_page_id, p_conversation_id, p_customer_psid, p_product_id, p_intro_version,
    p_source_ad_id, p_last_customer_interaction_at, p_intro_completed_at,
    v_due, v_expires, p_has_measurements
  ) returning * into v_cycle;
  insert into public.messenger_remarketing_logs(cycle_id, event, reason)
    values (v_cycle.id, 'scheduled', 'introduction_completed');
  return jsonb_build_object('started', true, 'cycle_id', v_cycle.id,
    'due_at', v_cycle.due_at, 'dry_run', v_config.dry_run);
end;
$$;

create or replace function public.remarketing_cancel_customer(
  p_page_id text,
  p_customer_psid text,
  p_reason text,
  p_has_measurements boolean default false
) returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare v_count integer;
begin
  update public.messenger_remarketing_cycles
    set status = 'cancelled', cancel_reason = left(p_reason, 80),
        has_measurements = has_measurements or p_has_measurements,
        claim_token = null, lease_until = null, completed_at = now(), updated_at = now()
    where page_id = p_page_id and customer_psid = p_customer_psid
      and status in ('scheduled', 'claimed');
  get diagnostics v_count = row_count;
  if v_count > 0 then
    insert into public.messenger_remarketing_logs(cycle_id, event, reason)
      select id, 'cancelled', left(p_reason, 80)
      from public.messenger_remarketing_cycles
      where page_id = p_page_id and customer_psid = p_customer_psid
        and status = 'cancelled' and updated_at >= now() - interval '2 seconds';
  end if;
  return v_count;
end;
$$;

create or replace function public.remarketing_preview_due(p_limit integer default 10)
returns table(cycle_id uuid, step smallint, due_at timestamptz, window_expires_at timestamptz)
language sql
security invoker
set search_path = ''
as $$
  select c.id, c.step, c.due_at, c.window_expires_at
  from public.messenger_remarketing_cycles c
  join public.messenger_remarketing_config cfg on cfg.singleton = true
  join public.conversations conv on conv.id = c.conversation_id
  join public.products p on p.id = c.product_id
  where cfg.enabled and cfg.dry_run and c.status = 'scheduled' and c.due_at <= now()
    and c.window_expires_at > now() and not c.has_measurements and p.status = 'active'
    and conv.current_product_id = c.product_id
    and coalesce((select (s.value->>'enabled')::boolean from public.app_settings s
      where s.key = 'auto_reply_enabled'), true)
    and not exists (select 1 from public.orders o where o.conversation_id = c.conversation_id)
  order by c.due_at, c.id
  limit greatest(1, least(p_limit, 25));
$$;

create or replace function public.remarketing_claim_due(
  p_limit integer default 10,
  p_lease_seconds integer default 45
) returns table(
  cycle_id uuid, attempt_id uuid, claim_token uuid, customer_psid text,
  conversation_id uuid, product_id bigint, step smallint,
  window_expires_at timestamptz, idempotency_key uuid
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_cycle public.messenger_remarketing_cycles;
  v_attempt public.messenger_remarketing_attempts;
  v_token uuid;
begin
  update public.messenger_remarketing_attempts a
    set status = 'uncertain', error_class = 'lease_expired', completed_at = now(), updated_at = now()
    from public.messenger_remarketing_cycles c
    where a.cycle_id = c.id and a.step = c.step and a.status = 'sending'
      and c.status = 'claimed' and c.lease_until < now();
  update public.messenger_remarketing_cycles
    set status = 'uncertain', last_error_class = 'lease_expired',
        completed_at = now(), claim_token = null, lease_until = null, updated_at = now()
    where status = 'claimed' and lease_until < now();

  update public.messenger_remarketing_cycles c
    set status = 'cancelled', cancel_reason = case
      when c.window_expires_at <= now() then 'window_expired'
      when not cfg.enabled then 'disabled'
      when cfg.dry_run then 'dry_run_only'
      when not coalesce((s.value->>'enabled')::boolean, true) then 'bot_disabled'
      when p.status <> 'active' then 'product_inactive'
      when conv.current_product_id is distinct from c.product_id then 'product_changed'
      when exists (select 1 from public.orders o where o.conversation_id = c.conversation_id) then 'order_exists'
      else c.cancel_reason end,
      completed_at = now(), claim_token = null, lease_until = null, updated_at = now()
    from public.messenger_remarketing_config cfg
    join public.conversations conv on true
    join public.products p on true
    left join public.app_settings s on s.key = 'auto_reply_enabled'
    where cfg.singleton = true and conv.id = c.conversation_id and p.id = c.product_id
      and c.status = 'scheduled' and (
        c.window_expires_at <= now() or not cfg.enabled or cfg.dry_run
        or not coalesce((s.value->>'enabled')::boolean, true)
        or p.status <> 'active' or conv.current_product_id is distinct from c.product_id
        or exists (select 1 from public.orders o where o.conversation_id = c.conversation_id)
      );

  for v_cycle in
    select c.* from public.messenger_remarketing_cycles c
    join public.messenger_remarketing_config cfg on cfg.singleton = true
    where cfg.enabled and not cfg.dry_run and c.status = 'scheduled'
      and c.due_at <= now() and c.window_expires_at > now() and not c.has_measurements
    order by c.due_at, c.id
    for update of c skip locked
    limit greatest(1, least(p_limit, 25))
  loop
    v_token := gen_random_uuid();
    insert into public.messenger_remarketing_attempts(cycle_id, step, status, claimed_at)
      values (v_cycle.id, v_cycle.step, 'sending', now())
      on conflict on constraint messenger_remarketing_attempts_cycle_id_step_key do update
        set status = 'sending', claimed_at = now(), updated_at = now()
        where public.messenger_remarketing_attempts.status = 'retryable'
      returning * into v_attempt;
    if not found then continue; end if;
    update public.messenger_remarketing_cycles
      set status = 'claimed', claim_token = v_token, claimed_at = now(),
          lease_until = now() + make_interval(secs => greatest(10, least(p_lease_seconds, 120))), updated_at = now()
      where id = v_cycle.id;
    cycle_id := v_cycle.id; attempt_id := v_attempt.id; claim_token := v_token;
    customer_psid := v_cycle.customer_psid; conversation_id := v_cycle.conversation_id;
    product_id := v_cycle.product_id; step := v_cycle.step;
    window_expires_at := v_cycle.window_expires_at; idempotency_key := v_attempt.idempotency_key;
    return next;
  end loop;
end;
$$;

create or replace function public.remarketing_validate_claim(
  p_cycle_id uuid,
  p_claim_token uuid
) returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_cycle public.messenger_remarketing_cycles;
  v_reason text;
begin
  select * into v_cycle from public.messenger_remarketing_cycles
    where id = p_cycle_id for update;
  if not found or v_cycle.status <> 'claimed' or v_cycle.claim_token is distinct from p_claim_token then
    return jsonb_build_object('valid', false, 'reason', 'claim_lost');
  end if;
  select case
    when v_cycle.lease_until <= now() then 'lease_expired'
    when v_cycle.window_expires_at <= now() then 'window_expired'
    when v_cycle.has_measurements then 'measurements_known'
    when not cfg.enabled or cfg.dry_run then 'disabled'
    when not coalesce((s.value->>'enabled')::boolean, true) then 'bot_disabled'
    when p.status <> 'active' then 'product_inactive'
    when conv.current_product_id is distinct from v_cycle.product_id then 'product_changed'
    when exists (select 1 from public.orders o where o.conversation_id = v_cycle.conversation_id) then 'order_exists'
  end into v_reason
  from public.messenger_remarketing_config cfg
  join public.conversations conv on conv.id = v_cycle.conversation_id
  join public.products p on p.id = v_cycle.product_id
  left join public.app_settings s on s.key = 'auto_reply_enabled'
  where cfg.singleton = true;
  if v_reason is not null then
    update public.messenger_remarketing_cycles set status = 'cancelled', cancel_reason = v_reason,
      claim_token = null, lease_until = null, completed_at = now(), updated_at = now()
      where id = v_cycle.id;
    update public.messenger_remarketing_attempts set status = 'failed', error_class = v_reason,
      completed_at = now(), updated_at = now()
      where cycle_id = v_cycle.id and step = v_cycle.step and status = 'sending';
    return jsonb_build_object('valid', false, 'reason', v_reason);
  end if;
  return jsonb_build_object('valid', true);
end;
$$;

create or replace function public.remarketing_complete_attempt(
  p_cycle_id uuid,
  p_claim_token uuid,
  p_message_id text
) returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_cycle public.messenger_remarketing_cycles;
  v_config public.messenger_remarketing_config;
  v_due timestamptz;
begin
  select * into v_cycle from public.messenger_remarketing_cycles where id = p_cycle_id for update;
  if not found then return jsonb_build_object('completed', false, 'reason', 'missing'); end if;
  update public.messenger_remarketing_attempts set status = 'sent', message_id = p_message_id,
    completed_at = now(), updated_at = now()
    where cycle_id = p_cycle_id and step = v_cycle.step and status = 'sending';
  if v_cycle.status <> 'claimed' or v_cycle.claim_token is distinct from p_claim_token then
    insert into public.messenger_remarketing_logs(cycle_id, event, reason)
      values (p_cycle_id, 'sent_after_cancel', 'claim_lost_during_send');
    return jsonb_build_object('completed', false, 'reason', 'claim_lost_after_send');
  end if;
  select * into v_config from public.messenger_remarketing_config where singleton = true;
  if v_cycle.step < v_config.max_steps then
    v_due := public.remarketing_effective_due(
      v_cycle.last_customer_interaction_at + make_interval(mins => v_config.second_delay_minutes),
      v_cycle.window_expires_at, v_config.quiet_start, v_config.quiet_end
    );
  end if;
  if v_due is not null and v_due > now() and v_due < v_cycle.window_expires_at then
    update public.messenger_remarketing_cycles set status = 'scheduled', step = step + 1,
      due_at = v_due, claim_token = null, claimed_at = null, lease_until = null, updated_at = now()
      where id = p_cycle_id;
    insert into public.messenger_remarketing_logs(cycle_id, event, reason)
      values (p_cycle_id, 'sent', 'next_step_scheduled');
    return jsonb_build_object('completed', true, 'next_step', v_cycle.step + 1, 'due_at', v_due);
  end if;
  update public.messenger_remarketing_cycles set status = 'completed', claim_token = null,
    lease_until = null, completed_at = now(), updated_at = now() where id = p_cycle_id;
  insert into public.messenger_remarketing_logs(cycle_id, event, reason)
    values (p_cycle_id, 'sent', 'cycle_completed');
  return jsonb_build_object('completed', true, 'next_step', null);
end;
$$;

create or replace function public.remarketing_fail_attempt(
  p_cycle_id uuid,
  p_claim_token uuid,
  p_error_class text,
  p_error_code text default null
) returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_cycle public.messenger_remarketing_cycles;
  v_attempt public.messenger_remarketing_attempts;
  v_retry_at timestamptz;
begin
  select * into v_cycle from public.messenger_remarketing_cycles
    where id = p_cycle_id and status = 'claimed' and claim_token = p_claim_token for update;
  if not found then return jsonb_build_object('updated', false, 'reason', 'claim_lost'); end if;
  select * into v_attempt from public.messenger_remarketing_attempts
    where cycle_id = p_cycle_id and step = v_cycle.step for update;
  if p_error_class = 'retryable' and v_attempt.retry_count < 1 then
    v_retry_at := now() + interval '10 minutes';
    if v_retry_at < v_cycle.window_expires_at then
      update public.messenger_remarketing_attempts set status = 'retryable', retry_count = retry_count + 1,
        error_class = p_error_class, error_code = left(p_error_code, 80), updated_at = now()
        where id = v_attempt.id;
      update public.messenger_remarketing_cycles set status = 'scheduled', due_at = v_retry_at,
        claim_token = null, claimed_at = null, lease_until = null,
        last_error_class = p_error_class, last_error_code = left(p_error_code, 80), updated_at = now()
        where id = p_cycle_id;
      return jsonb_build_object('updated', true, 'retry', true, 'due_at', v_retry_at);
    end if;
  end if;
  update public.messenger_remarketing_attempts set status = case
      when p_error_class = 'uncertain' then 'uncertain' else 'failed' end,
    error_class = left(p_error_class, 80), error_code = left(p_error_code, 80),
    completed_at = now(), updated_at = now() where id = v_attempt.id;
  update public.messenger_remarketing_cycles set status = case
      when p_error_class = 'uncertain' then 'uncertain' else 'failed' end,
    claim_token = null, lease_until = null, completed_at = now(),
    last_error_class = left(p_error_class, 80), last_error_code = left(p_error_code, 80), updated_at = now()
    where id = p_cycle_id;
  insert into public.messenger_remarketing_logs(cycle_id, event, reason)
    values (p_cycle_id, case when p_error_class = 'uncertain' then 'uncertain' else 'failed' end,
      left(p_error_class, 80));
  return jsonb_build_object('updated', true, 'retry', false);
end;
$$;

create or replace function public.remarketing_update_config(
  p_enabled boolean,
  p_dry_run boolean,
  p_max_steps smallint default 1
) returns public.messenger_remarketing_config
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_before public.messenger_remarketing_config;
  v_after public.messenger_remarketing_config;
begin
  select * into v_before from public.messenger_remarketing_config where singleton = true for update;
  if not p_enabled then
    update public.messenger_remarketing_cycles set status = 'cancelled', cancel_reason = 'disabled',
      claim_token = null, lease_until = null, completed_at = now(), updated_at = now()
      where status in ('scheduled', 'claimed');
  elsif not p_dry_run and (not v_before.enabled or v_before.dry_run) then
    update public.messenger_remarketing_cycles set status = 'cancelled', cancel_reason = 'production_rollout_reset',
      claim_token = null, lease_until = null, completed_at = now(), updated_at = now()
      where status in ('scheduled', 'claimed');
  end if;
  update public.messenger_remarketing_config set enabled = p_enabled, dry_run = p_dry_run,
    max_steps = greatest(1, least(p_max_steps, 2)),
    rollout_at = case when p_enabled and (not v_before.enabled or v_before.dry_run is distinct from p_dry_run)
      then now() when p_enabled then v_before.rollout_at else null end,
    updated_at = now()
    where singleton = true returning * into v_after;
  return v_after;
end;
$$;

create or replace function public.remarketing_status()
returns jsonb
language sql
security invoker
set search_path = ''
as $$
  select to_jsonb(cfg) || jsonb_build_object(
    'scheduled_count', (select count(*) from public.messenger_remarketing_cycles where status = 'scheduled'),
    'claimed_count', (select count(*) from public.messenger_remarketing_cycles where status = 'claimed'),
    'uncertain_count', (select count(*) from public.messenger_remarketing_cycles where status = 'uncertain')
  ) from public.messenger_remarketing_config cfg where singleton = true;
$$;

create or replace function public.remarketing_cleanup()
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare v_logs integer; v_outbound integer; v_cycles integer;
begin
  delete from public.messenger_remarketing_logs where created_at < now() - interval '14 days';
  get diagnostics v_logs = row_count;
  delete from public.messenger_bot_outbound where created_at < now() - interval '14 days';
  get diagnostics v_outbound = row_count;
  delete from public.messenger_remarketing_cycles
    where status not in ('scheduled', 'claimed') and completed_at < now() - interval '30 days';
  get diagnostics v_cycles = row_count;
  return jsonb_build_object('logs', v_logs, 'outbound', v_outbound, 'cycles', v_cycles);
end;
$$;

create or replace function public.remarketing_cancel_on_order()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  update public.messenger_remarketing_cycles set status = 'cancelled', cancel_reason = 'order_created',
    claim_token = null, lease_until = null, completed_at = now(), updated_at = now()
    where conversation_id = new.conversation_id and status in ('scheduled', 'claimed');
  return new;
end;
$$;

create or replace function public.remarketing_cancel_on_product_change()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if old.current_product_id is distinct from new.current_product_id then
    update public.messenger_remarketing_cycles set status = 'cancelled', cancel_reason = 'product_changed',
      claim_token = null, lease_until = null, completed_at = now(), updated_at = now()
      where conversation_id = new.id and status in ('scheduled', 'claimed')
        and product_id is distinct from new.current_product_id;
  end if;
  return new;
end;
$$;

create or replace function public.remarketing_cancel_on_product_inactive()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if old.status is distinct from new.status and new.status <> 'active' then
    update public.messenger_remarketing_cycles set status = 'cancelled', cancel_reason = 'product_inactive',
      claim_token = null, lease_until = null, completed_at = now(), updated_at = now()
      where product_id = new.id and status in ('scheduled', 'claimed');
  end if;
  return new;
end;
$$;

create or replace function public.remarketing_cancel_on_bot_setting()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.key = 'auto_reply_enabled' and not coalesce((new.value->>'enabled')::boolean, true) then
    update public.messenger_remarketing_cycles set status = 'cancelled', cancel_reason = 'bot_disabled',
      claim_token = null, lease_until = null, completed_at = now(), updated_at = now()
      where status in ('scheduled', 'claimed');
  end if;
  return new;
end;
$$;

