-- Messenger remarketing is installed disabled. Production activation is a
-- separate, explicit step after the authenticated endpoint has been verified.
create extension if not exists pg_net;
create extension if not exists pg_cron with schema pg_catalog;
grant usage on schema cron to postgres;
grant all privileges on all tables in schema cron to postgres;

create table public.messenger_remarketing_config (
  singleton boolean primary key default true check (singleton),
  enabled boolean not null default false,
  dry_run boolean not null default true,
  rollout_at timestamptz,
  target_product_ids bigint[] not null default array[16::bigint],
  first_delay_minutes integer not null default 120 check (first_delay_minutes between 5 and 1380),
  second_delay_minutes integer not null default 1080 check (second_delay_minutes between 5 and 1380),
  max_steps smallint not null default 1 check (max_steps between 1 and 2),
  quiet_start time not null default '21:00',
  quiet_end time not null default '08:00',
  window_safety_minutes integer not null default 10 check (window_safety_minutes between 1 and 120),
  updated_at timestamptz not null default now()
);

insert into public.messenger_remarketing_config(singleton) values (true)
on conflict (singleton) do nothing;

create table public.messenger_remarketing_cycles (
  id uuid primary key default gen_random_uuid(),
  page_id text not null,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  customer_psid text not null,
  product_id bigint not null references public.products(id) on delete cascade,
  intro_version text not null,
  source_ad_id text,
  status text not null default 'scheduled' check (status in (
    'scheduled', 'claimed', 'completed', 'cancelled', 'failed', 'uncertain'
  )),
  step smallint not null default 1 check (step between 1 and 2),
  last_customer_interaction_at timestamptz not null,
  intro_completed_at timestamptz not null,
  due_at timestamptz not null,
  window_expires_at timestamptz not null,
  has_measurements boolean not null default false,
  claim_token uuid,
  claimed_at timestamptz,
  lease_until timestamptz,
  cancel_reason text,
  last_error_class text,
  last_error_code text,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(page_id, customer_psid, product_id, intro_version)
);

create unique index messenger_remarketing_one_active_customer_idx
  on public.messenger_remarketing_cycles(page_id, customer_psid)
  where status in ('scheduled', 'claimed');
create index messenger_remarketing_due_idx
